package me.timschneeberger.rootlessjamesdsp.globalfx

import kotlin.math.abs

/**
 * A cubic Hermite curve through a set of nodes, with the slopes chosen the
 * way the Multiband EQ's engine chooses them (PCHIP or makima).
 *
 * Global mode cannot run the engine, so it has to draw the same curve the
 * engine would have drawn and hand that to Android's equaliser instead. Any
 * difference in slope rules would make the same card sound different in the
 * two modes, so this follows interpolation.c line for line, including its
 * one-sided end slopes. One deliberate difference: past the last node this
 * holds the end value instead of extending the last cubic, since the curve is
 * read up to the output's Nyquist frequency and an extended cubic can run off
 * to any value there.
 */
class HermiteCurve private constructor(
    private val x: DoubleArray,
    private val y: DoubleArray,
    private val s: DoubleArray,
) {
    fun valueAt(at: Double): Double {
        val n = x.size
        if (at >= x[n - 1]) return y[n - 1]
        if (at <= x[0]) return y[0]
        // First node strictly greater than at, as upper_bound in the C code.
        var lo = 0
        var hi = n
        while (lo < hi) {
            val mid = (lo + hi) ushr 1
            if (x[mid] <= at) lo = mid + 1 else hi = mid
        }
        var it = lo
        if (it == 0) it = 1
        if (it == n) it = n - 1
        val x0 = x[it - 1]
        val x1 = x[it]
        val y0 = y[it - 1]
        val y1 = y[it]
        val s0 = s[it - 1]
        val s1 = s[it]
        val dx = x1 - x0
        val t = (at - x0) / dx
        return (1.0 - t) * (1.0 - t) * (y0 * (1.0 + 2.0 * t) + s0 * (at - x0)) +
            t * t * (y1 * (3.0 - 2.0 * t) + dx * s1 * (t - 1.0))
    }

    companion object {
        /** Fritsch and Carlson (1980) monotone slopes, as pchip() in interpolation.c. */
        fun pchip(x: DoubleArray, y: DoubleArray): HermiteCurve {
            require(x.size == y.size && x.size >= 4) { "pchip needs at least four nodes" }
            val n = x.size
            val s = DoubleArray(n)
            s[0] = (y[1] - y[0]) / (x[1] - x[0])
            for (k in 1 until n - 1) {
                val hkm1 = x[k] - x[k - 1]
                val dkm1 = (y[k] - y[k - 1]) / hkm1
                val hk = x[k + 1] - x[k]
                val dk = (y[k + 1] - y[k]) / hk
                val w1 = 2.0 * hk + hkm1
                val w2 = hk + 2.0 * hkm1
                s[k] = if ((dk > 0 && dkm1 < 0.0) || (dk < 0.0 && dkm1 > 0.0) || dk == 0.0 || dkm1 == 0.0)
                    0.0
                else
                    (w1 + w2) / (w1 / dkm1 + w2 / dk)
            }
            s[n - 1] = (y[n - 1] - y[n - 2]) / (x[n - 1] - x[n - 2])
            return HermiteCurve(x.copyOf(), y.copyOf(), s)
        }

        /** Modified Akima slopes, as makima() in interpolation.c. */
        fun makima(x: DoubleArray, y: DoubleArray): HermiteCurve {
            require(x.size == y.size && x.size >= 4) { "makima needs at least four nodes" }
            val n = x.size
            val s = DoubleArray(n)
            fun weighted(wa: Double, a: Double, wb: Double, b: Double) =
                if (wa + wb < EPSILON) 0.0 else (wa * a + wb * b) / (wa + wb)

            val m2 = (y[3] - y[2]) / (x[3] - x[2])
            val m1 = (y[2] - y[1]) / (x[2] - x[1])
            val m0 = (y[1] - y[0]) / (x[1] - x[0])
            val mm1 = 2.0 * m0 - m1
            val mm2 = 2.0 * mm1 - m0
            var w1 = abs(m1 - m0) + abs(m1 + m0) * 0.5
            var w2 = abs(mm1 - mm2) + abs(mm1 + mm2) * 0.5
            s[0] = weighted(w1, mm1, w2, m0)

            w1 = abs(m2 - m1) + abs(m2 + m1) * 0.5
            w2 = abs(m0 - mm1) + abs(m0 + mm1) * 0.5
            s[1] = weighted(w1, m0, w2, m1)
            for (i in 2 until n - 2) {
                val mim2 = (y[i - 1] - y[i - 2]) / (x[i - 1] - x[i - 2])
                val mim1 = (y[i] - y[i - 1]) / (x[i] - x[i - 1])
                val mi = (y[i + 1] - y[i]) / (x[i + 1] - x[i])
                val mip1 = (y[i + 2] - y[i + 1]) / (x[i + 2] - x[i + 1])
                w1 = abs(mip1 - mi) + abs(mip1 + mi) * 0.5
                w2 = abs(mim1 - mim2) + abs(mim1 + mim2) * 0.5
                s[i] = weighted(w1, mim1, w2, mi)
            }
            val mnm4 = (y[n - 3] - y[n - 4]) / (x[n - 3] - x[n - 4])
            val mnm3 = (y[n - 2] - y[n - 3]) / (x[n - 2] - x[n - 3])
            val mnm2 = (y[n - 1] - y[n - 2]) / (x[n - 1] - x[n - 2])
            val mnm1 = 2.0 * mnm2 - mnm3
            val mn = 2.0 * mnm1 - mnm2
            w1 = abs(mnm1 - mnm2) + abs(mnm1 + mnm2) * 0.5
            w2 = abs(mnm3 - mnm4) + abs(mnm3 + mnm4) * 0.5
            s[n - 2] = weighted(w1, mnm3, w2, mnm2)

            w1 = abs(mn - mnm1) + abs(mn + mnm1) * 0.5
            w2 = abs(mnm2 - mnm3) + abs(mnm2 + mnm3) * 0.5
            s[n - 1] = weighted(w1, mnm2, w2, mnm1)
            return HermiteCurve(x.copyOf(), y.copyOf(), s)
        }

        // DBL_EPSILON, as the C code compares against
        private const val EPSILON = 2.220446049250313e-16
    }
}
